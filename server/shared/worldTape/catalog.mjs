/** The catalog: feeds (their metadata, not their code) and the extras. */
export function buildCatalog(feeds = WORLD_TAPE_FEEDS) {
  return [
    ...feeds.map(
      ({ id, label, layers, kind, class: cls, licence, cadenceMs, phase }) => ({
        id,
        label,
        layers,
        kind,
        class: cls,
        licence,
        cadenceMs,
        phase,
      }),
    ),
    ...EXTRA_ITEMS,
  ];
}

/** The feeds by id. */
export function feedMap(feeds = WORLD_TAPE_FEEDS) {
  return new Map(feeds.map((feed) => [feed.id, feed]));
}
